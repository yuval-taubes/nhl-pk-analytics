CREATE INDEX IF NOT EXISTS idx_mp_shots_pk_against
    ON mp_shots (defending_team_code, season, game_id)
    WHERE shooting_skaters > defending_skaters AND defending_skaters IN (3, 4);

CREATE INDEX IF NOT EXISTS idx_mp_shots_goalie
    ON mp_shots (goalie_id_for_shot, season)
    WHERE goalie_id_for_shot IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_mp_shots_last_event
    ON mp_shots (last_event_category, season);

CREATE INDEX IF NOT EXISTS idx_mp_skaters_pk
    ON mp_skaters_season (situation, season, player_id);

CREATE INDEX IF NOT EXISTS idx_mp_team_games_pk
    ON mp_team_games (situation, season, team);
