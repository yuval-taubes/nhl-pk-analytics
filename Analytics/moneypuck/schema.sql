-- MoneyPuck v2 side-by-side schema.
-- These tables intentionally do not replace the original NHL API schema.

CREATE TABLE IF NOT EXISTS mp_import_runs (
    import_id SERIAL PRIMARY KEY,
    source_root TEXT NOT NULL,
    imported_at TIMESTAMP DEFAULT NOW(),
    shots_rows INTEGER DEFAULT 0,
    team_game_rows INTEGER DEFAULT 0,
    skater_rows INTEGER DEFAULT 0,
    goalie_rows INTEGER DEFAULT 0,
    team_season_rows INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS mp_shots (
    season INTEGER NOT NULL,
    game_id INTEGER NOT NULL,
    shot_id INTEGER NOT NULL,
    home_team_code VARCHAR(8),
    away_team_code VARCHAR(8),
    is_playoff_game BOOLEAN,
    home_team_won BOOLEAN,
    period INTEGER,
    time_seconds INTEGER,
    event VARCHAR(16),
    shooting_team_code VARCHAR(8),
    defending_team_code VARCHAR(8),
    is_home_shot BOOLEAN,
    home_goals INTEGER,
    away_goals INTEGER,
    home_skaters INTEGER,
    away_skaters INTEGER,
    shooting_skaters INTEGER,
    defending_skaters INTEGER,
    strength_state VARCHAR(8),
    x_cord NUMERIC,
    y_cord NUMERIC,
    x_cord_adjusted NUMERIC,
    y_cord_adjusted NUMERIC,
    arena_adjusted_x_cord NUMERIC,
    arena_adjusted_y_cord NUMERIC,
    shot_angle NUMERIC,
    shot_angle_adjusted NUMERIC,
    shot_distance NUMERIC,
    shot_type VARCHAR(32),
    goal BOOLEAN,
    shot_was_on_goal BOOLEAN,
    shot_on_empty_net BOOLEAN,
    shot_rebound BOOLEAN,
    shot_generated_rebound BOOLEAN,
    shot_rush BOOLEAN,
    shot_goalie_froze BOOLEAN,
    shot_play_stopped BOOLEAN,
    shot_play_continued_in_zone BOOLEAN,
    shot_play_continued_outside_zone BOOLEAN,
    shot_angle_rebound_royal_road BOOLEAN,
    shot_angle_plus_rebound_speed NUMERIC,
    off_wing BOOLEAN,
    x_goal NUMERIC,
    x_froze NUMERIC,
    x_rebound NUMERIC,
    x_play_stopped NUMERIC,
    x_play_continued_in_zone NUMERIC,
    x_play_continued_outside_zone NUMERIC,
    x_shot_was_on_goal NUMERIC,
    time_since_last_event NUMERIC,
    time_until_next_event NUMERIC,
    time_since_faceoff NUMERIC,
    time_difference_since_change NUMERIC,
    shooter_player_id INTEGER,
    shooter_name TEXT,
    shooter_left_right VARCHAR(8),
    shooter_time_on_ice NUMERIC,
    shooter_time_on_ice_since_faceoff NUMERIC,
    goalie_id_for_shot INTEGER,
    goalie_name_for_shot TEXT,
    shooting_team_average_time_on_ice NUMERIC,
    shooting_team_max_time_on_ice NUMERIC,
    defending_team_average_time_on_ice NUMERIC,
    defending_team_max_time_on_ice NUMERIC,
    defending_team_average_time_on_ice_since_faceoff NUMERIC,
    defending_team_max_time_on_ice_since_faceoff NUMERIC,
    home_penalty1_time_left NUMERIC,
    home_penalty1_length NUMERIC,
    away_penalty1_time_left NUMERIC,
    away_penalty1_length NUMERIC,
    last_event_category VARCHAR(32),
    last_event_team VARCHAR(16),
    last_event_x_cord NUMERIC,
    last_event_y_cord NUMERIC,
    last_event_x_cord_adjusted NUMERIC,
    last_event_y_cord_adjusted NUMERIC,
    distance_from_last_event NUMERIC,
    speed_from_last_event NUMERIC,
    PRIMARY KEY (season, game_id, shot_id)
);

